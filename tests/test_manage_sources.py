    after = (config_dir / "tags.yaml").read_text(encoding="utf-8")
    assert after == before
    assert "ai-safety" not in _tags(config_dir)["domains"]
    # The topic/source config is still created — only the tag seed is skipped.
    assert "ai-safety" in {t.name for t in ms.list_state(config_dir).topics}


