def test_add_source_idempotent_on_url_variant(config_dir):
    # Source identity follows the dedup contract (normalize_url): an http/https,
    # www or trailing-slash VARIANT of an existing feed must NOT add a second
    # record (which would silently collect the same feed twice).
    ms.add_topic(config_dir, "ai-agents")
    ms.add_source(config_dir, topic="ai-agents", url="http://dup.example/feed",
                  source_type="rss", tier="medium", priority="medium",
                  filter_note="x", active=True)
    added = ms.add_source(config_dir, topic="ai-agents", url="https://www.dup.example/feed/",
                          source_type="rss", tier="medium", priority="medium",
                          filter_note="x", active=True)
    assert added is False
    # The original raw URL is preserved; no duplicate variant record was written.
    assert _all_urls(config_dir) == {"http://dup.example/feed"}
    assert _sources_yaml(config_dir).count("dup.example/feed") == 1


