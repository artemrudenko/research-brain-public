def test_set_active_only_touches_target_record(config_dir):
    ms.add_topic(config_dir, "ai-agents")
    keep = "https://keep.example/feed"
    target = "https://target.example/feed"
    for u in (keep, target):
        ms.add_source(
            config_dir, "ai-agents", u, source_type="rss", tier="medium",
            priority="medium", filter_note="x", active=True,
        )
    keep_before = _source_by_url(config_dir, keep)
    ms.set_source_active(config_dir, target, active=False)
    # The sibling record is byte-for-byte untouched (still active); only the
    # target flipped.
    assert _source_by_url(config_dir, keep) == keep_before
    assert _source_by_url(config_dir, keep).active is True
    assert _source_by_url(config_dir, target).active is False


