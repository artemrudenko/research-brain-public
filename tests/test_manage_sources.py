def test_add_topic_writes_config_atomically(config_dir, monkeypatch):
    # The config writes must go through registry.atomic_write_text (same-dir temp +
    # os.replace) so a crash mid-write can't truncate topics.yaml / sources.yaml.
    calls: list[Path] = []
    real = ms.atomic_write_text

    def _spy(path: Path, text: str) -> None:
        calls.append(path)
        real(path, text)

    monkeypatch.setattr(ms, "atomic_write_text", _spy)
    ms.add_topic(config_dir, "ai-agents")

    written = {p.name for p in calls}
    assert {"topics.yaml", "sources.yaml"} <= written  # both config files via the helper
    # Content is still correct after the atomic write.
    topics, cats = _yaml_state(config_dir)
    assert "ai-agents" in {t.name for t in topics}
    assert "ai-agents" in {c.name for c in cats}


