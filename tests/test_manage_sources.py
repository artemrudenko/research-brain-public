def test_add_topic_does_not_seed_a_domain_colliding_with_a_synonym(config_dir):
    # The shipped registry maps the alias `ai-safety` -> `ai/governance`. A topic
    # named `ai-safety` must NOT create a `domains: ai-safety` key: the alias
    # already normalizes to a canonical domain tag, so seeding a bare domain
    # would shadow the synonym. tags.yaml must be left byte-for-byte unchanged.
    before = (config_dir / "tags.yaml").read_text(encoding="utf-8")
