# A test-owned snapshot of the EXAMPLE config, NOT the live `config/`. Seeding
# fixtures from a fixed snapshot keeps these tests hermetic: they pass the same
# in the pristine template and in a configured deployment whose real `config/`
# no longer contains the shipped example rows. The YAML twins in the snapshot
# were generated by the real migrator from the legacy .md templates — EXAMPLE
# placeholder rows are excluded at migration time, so a fresh install starts
# EMPTY. The .md files remain in the snapshot only as legacy-template specimens
# (migrator input / refusal tests).
EXAMPLE_CONFIG = Path(__file__).resolve().parent / "fixtures" / "example_config"


# --------------------------------------------------------------------------- #
# Fixtures — a temp config/ dir seeded from the shipped templates.
# --------------------------------------------------------------------------- #


@pytest.fixture
def config_dir(tmp_path: Path) -> Path:
    """A throwaway config/ dir holding copies of the shipped YAML config + tags."""
    d = tmp_path / "config"
    d.mkdir()
    # The shipped 0.8.0 template: the YAML twins (empty structures) plus the
    # controlled vocabulary, so add_topic can seed a tag into it.
    for name in ("sources.yaml", "topics.yaml", "tags.yaml"):
        (d / name).write_text(
            (EXAMPLE_CONFIG / name).read_text(encoding="utf-8"),
            encoding="utf-8",
        )
    return d


def _tags(config_dir: Path):
    """Parse the temp tags.yaml back into a dict (proves it still loads)."""
    import yaml

    return yaml.safe_load((config_dir / "tags.yaml").read_text(encoding="utf-8"))


def _sources_yaml(config_dir: Path) -> str:
    return (config_dir / "sources.yaml").read_text(encoding="utf-8")


def _topics_yaml(config_dir: Path) -> str:
    return (config_dir / "topics.yaml").read_text(encoding="utf-8")


def _yaml_state(config_dir: Path) -> tuple[list[Topic], list[Category]]:
    """Load both YAML twins through the store (the parse every reader uses)."""
    return (
        store.load_topics(config_dir / "topics.yaml"),
        store.load_categories(config_dir / "sources.yaml"),
    )


def _all_urls(config_dir: Path) -> set[str]:
    _, cats = _yaml_state(config_dir)
    return {s.url for c in cats for s in c.sources}


def _source_by_url(config_dir: Path, url: str) -> Source:
    _, cats = _yaml_state(config_dir)
    return next(s for c in cats for s in c.sources if s.url == url)


