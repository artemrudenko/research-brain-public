"""
test_manage_sources.py — offline tests for the source-manage mutation engine.

Covers the conversational `source-manage` skill's deterministic backend
(`scripts/manage_sources.py`) against the YAML-only config (0.8.0+): adding
topics/sources, pause/resume, removing topics, topics.yaml <-> sources.yaml
name sync, idempotency, malformed-input rejection, the loud refusal of an
unmigrated legacy .md dir (the `migrate-config` pointer), and that a mutation
round-trip still passes the shipped YAML validators.

All mutations run against a temp copy of config/; the real config/ is never
touched (TDD-safe, parallel-safe).
"""
