"""
api.py — the typed contract of the validate_config.py facade.

The config-validation CLI receives the stable facade module as `api` (the
facade re-exports every validator plus the lazy PyYAML import, and tests
monkeypatch names on it). `ConfigValidationApi` types that seam — exactly the
attributes the CLI reads, no more. Runtime-checkable so the test suite can
assert the real facade satisfies it.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Protocol, runtime_checkable

if TYPE_CHECKING:
    from pathlib import Path
    from types import ModuleType


@runtime_checkable
class ConfigValidationApi(Protocol):
    """Everything the config-validation CLI reads off the facade module."""

    # --- constants ---------------------------------------------------------- #
    @property
    def DEFAULT_CONFIG_DIR(self) -> str: ...
    @property
    def PROJECT_ROOT(self) -> Path: ...

    # --- environment -------------------------------------------------------- #
    def _load_yaml(self) -> ModuleType: ...

    # --- active-format resolution (CONVENTIONS §2.3) ------------------------- #
    def active_sources_path(self, config_dir: Path) -> Path: ...
    def active_topics_path(self, config_dir: Path) -> Path: ...
    def legacy_md_needs_migration(self, config_dir: Path) -> bool: ...

    # --- schema validators ---------------------------------------------------- #
    def validate_channels(self, path: Path, yaml: ModuleType) -> list[str]: ...
    def validate_schedule(self, path: Path, yaml: ModuleType) -> list[str]: ...
    def validate_sources_yaml(self, path: Path, yaml: ModuleType) -> list[str]: ...
    def validate_topics_yaml(self, path: Path, yaml: ModuleType) -> list[str]: ...
    def validate_tags(self, path: Path, yaml: ModuleType) -> list[str]: ...
    def validate_search(self, path: Path, yaml: ModuleType) -> list[str]: ...
    def validate_glossary(self, path: Path, yaml: ModuleType) -> list[str]: ...
    def validate_authors_yaml(self, path: Path, yaml: ModuleType) -> list[str]: ...

    # --- scans / advisory checks ------------------------------------------------ #
    def detect_inline_secrets(self, config_dir: Path) -> list[str]: ...
    def detect_placeholders(self, config_dir: Path) -> list[str]: ...
    def check_topics_sources_sync(
        self, topics_path: Path, sources_path: Path
    ) -> list[str]: ...
    def check_config_format_sync(self, config_dir: Path) -> list[str]: ...

    # --- opt-in feed liveness probe (--check-feeds) ------------------------------ #
    def extract_source_urls(self, sources_path: Path) -> list[str]: ...
    def check_feed_liveness(self, urls: list[str]) -> list[str]: ...


__all__ = ["ConfigValidationApi"]
